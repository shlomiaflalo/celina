/** Перевод одного слова-сущности (кухня/блюдо/имя/город) или контент-словарь. */
function trEntity(s: string): string {
  return KITCHEN_EN[s] ?? DISH_EN[s] ?? NAME_EN[s] ?? CITY_EN[s] ?? contentEn[s] ?? s;
}

export function translateContent(value: string, lang: Lang): string {
  if (lang !== "en") return value; // контент хранится на русском → в RU отдаём как есть
  if (contentEn[value]) return contentEn[value];
  // шаблоны био/описаний — переводим ядро и подставляем
  let m = value.match(/^(.+) — домашняя еда с душой\.$/);
  if (m) return `${trEntity(m[1])} — homemade food with soul.`;
  m = value.match(/^(.+) — по домашнему рецепту\.$/);
  if (m) return `${trEntity(m[1])} — a homemade recipe.`;
  return trEntity(value);
}

export function useTr() {
  const { lang } = useContext(LangCtx);
  return (value?: string | null): string => {
    if (!value) return "";
    return translateContent(value, lang);
  };
}
