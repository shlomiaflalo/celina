/** Русское склонение по числу: plRu(2, ["место", "места", "мест"]) → "места".
 *  Формы: [1, 2–4, 5+] с учётом 11–14 → всегда третья форма. */
export function plRu(n: number, forms: [string, string, string]): string {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 4 && a < 20) return forms[2];
  if (b === 1) return forms[0];
  if (b >= 2 && b <= 4) return forms[1];
  return forms[2];
}

