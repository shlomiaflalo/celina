/** Координаты выбранного города или null. */
export function cityCoords(name: string | null | undefined): { lat: number; lng: number } | null {
  if (!name) return null;
  const hit = CITY_COORDS[name.trim()];
  return hit ? { lat: hit[0], lng: hit[1] } : null;
}

/** Расстояние между точками в метрах (формула гаверсинуса). */
export function haversineM(a: { lat: number; lng: number }, b: { lat: number; lng: number }): number {
  const R = 6371000; // радиус Земли, м
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const lat1 = toRad(a.lat);
  const lat2 = toRad(b.lat);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2;
  return Math.round(2 * R * Math.asin(Math.sqrt(h)));
}
