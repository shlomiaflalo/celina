/**
 * Оформление дня.
 *
 * Каждое утро сайт одевается под РЕАЛЬНЫЙ повод: погоду в Москве, праздник,
 * день региональной кухни. Никогда — случайно: сайт, который меняется без
 * причины, читается как сломанный, а Селина продаёт доверие.
 *
 * Слой намеренно узкий. Тема умеет ровно две вещи: подменить несколько
 * CSS-переменных и переписать пару строк текста. Она физически не может
 * задеть заказы, корзину, оплату или верификацию — что бы ни придумал
 * дизайнер.
 *
 * Чем тема располагает. Строкой дня, плейсхолдером поиска, акцентом
 * `--day-accent` (его читает первый экран) и рисованной графикой дня —
 * `decor`, см. DayDecor.tsx. До 21.08.2026 рычагов не было вообще: тинт жил
 * на фотографии героя, а фотографию убрали ради LCP.
 *
 * Чего тема не умеет — и не должна. Рисовать поверх фотографии героя.
 * Декоративный слой (косые штрихи «дождя», серо-синяя пелена поверх Красной
 * площади) на живом сайте читался не как погода, а как испорченная картинка:
 * тёплый оранжевый бренд гас, фото выглядело поцарапанным. Повод дня живёт
 * в тексте и в акценте — фотография остаётся чистой.
 */

export interface DayTheme {
  /** Короткий id для дневника оформления. */
  id: string;
  /** Повод одной строкой — попадает в дневник и в пост. */
  occasion: string;
  /**
   * Переменные, которые тема вправе подменить (см. index.css).
   *
   * ВНИМАНИЕ (21.08.2026): сейчас НИ ОДНА из них никем не читается.
   * `--day-hero-tint` жил на фотографии героя, а фотографию с главной убрали
   * ради LCP — переменная осталась, лежать ей больше не на чем. Ставить их
   * бессмысленно: тема просто отрисует мёртвый <style>. Пока кто-нибудь не
   * проведёт `--day-accent` в компоненты, день живёт в тексте.
   */
  /**
   * ПРАВИЛО ОСНОВАТЕЛЯ (23.08.2026): у сайта ДВА цвета — фирменный оранжевый
   * #e0860c и белый/светлый фон. --day-accent НЕ должен уводить текст в
   * коричневый или любой другой оттенок: тёмный акцент #b56a08 на живом
   * сайте прочитался как «текст и оранжевый, и коричневый». Текст — только
   * цвет логотипа.
   */
  vars?: Partial<Record<"--day-accent" | "--day-hero-tint" | "--day-veil", string>>;
  /** Строка дня над поиском. Не заголовок и не реклама — реплика. */
  line?: { ru: string; en: string };
  /** Плейсхолдер поиска в голосе дня. */
  placeholder?: { ru: string; en: string };
  /**
   * Рисованная графика дня (см. DayDecor.tsx) — единственный визуальный
   * рычаг слоя после того, как с главной убрали фотографию героя.
   *
   * Не украшение ради украшения: декорация выпускается только вместе с
   * поводом, который её объясняет. Нет повода — нет и графики.
   *
   * ВАЖНО (22.08.2026, после трёх итераций с основателем): урожай на
   * главной остаётся, но (1) ТОЛЬКО в цветах логотипа — палитра --dc-* в
   * index.css теперь монохромно-оранжевая, не возвращать зелёный/красный;
   * (2) не сплошной стеной, а натюрмортами с воздухом. Сцена «общий стол»
   * (components/TableBand.tsx) забракована в пользу овощей и лежит в
   * запасе; рисовать на столе руки/людей нельзя.
   *
   * "breakfast" (25.08.2026) — поздний завтрак последней недели каникул:
   * сырники, кружка с паром, блины, банка варенья, каша, яблоко. Тот же
   * прилавок, другой натюрморт — формат дня, а не разовая графика.
   *
   * "perm" (26.08.2026) — пермский прилавок: пельмень-ушко, миска, посикунчик,
   * шаньга, груздь. Третий натюрморт того же прилавка — формат дня.
   */
  decor?: "harvest" | "breakfast" | "perm";
}

