/**
 * Оформление дня.
 *
 * Каждое утро сайт одевается под РЕАЛЬНЫЙ повод: погоду в Москве, праздник,
 * день региональной кухни. Никогда — случайно: сайт, который меняется без
 * причины, читается как сломанный, а Селина продаёт доверие.
 *
 * Слой намеренно узкий. Тема умеет ровно две вещи: подменить несколько
 * CSS-переменных и переписать пару строк текста. Она физически не может
 * задеть заказы, корзину, оплату или верификацию — что бы ни придумал
 * дизайнер.
 *
 * Чего тема не умеет — и не должна. Рисовать поверх фотографии героя.
 * Декоративный слой (косые штрихи «дождя», серо-синяя пелена поверх Красной
 * площади) на живом сайте читался не как погода, а как испорченная картинка:
 * тёплый оранжевый бренд гас, фото выглядело поцарапанным. Повод дня живёт
 * в тексте и в акценте — фотография остаётся чистой.
 */

export interface DayTheme {
  /** Короткий id для дневника оформления. */
  id: string;
  /** Повод одной строкой — попадает в дневник и в пост. */
  occasion: string;
  /** Переменные, которые тема вправе подменить (см. index.css). */
  vars?: Partial<Record<"--day-accent" | "--day-hero-tint" | "--day-veil", string>>;
  /** Строка дня над поиском. Не заголовок и не реклама — реплика. */
  line?: { ru: string; en: string };
  /** Плейсхолдер поиска в голосе дня. */
  placeholder?: { ru: string; en: string };
}

/** Обычный день: ничего не подменяем, сайт выглядит как всегда. */
export const NO_THEME: DayTheme = { id: "plain", occasion: "обычный день" };

