import { TODAY } from "./dayTheme";

/**
 * Применяет оформление дня: отдаёт CSS-переменные дня одним <style>.
 *
 * Почему не через JS в эффекте, как было раньше. Сайт собирается статикой
 * (vite-react-ssg, 102 страницы): браузер рисует готовый HTML задолго до
 * того, как доедет и оживёт бандл. Пока темы не трогали переменные, разницы
 * не было; в первый же день с `vars` (12.08) оттенок героя сначала показался
 * бы дефолтным и только на гидратации переехал в дневной — моргание ровно на
 * LCP-картинке. Переменные, отрисованные в разметку, приезжают вместе с
 * первым байтом и работают даже без JS.
 *
 * Блок объявлен после index.css по порядку документа, поэтому при равной
 * специфичности выигрывает он — дефолты из :root остаются запасным вариантом
 * на день без темы.
 */
export function DayThemeProvider() {
  const vars = TODAY.vars;
  if (!vars) return null;

  const decls = Object.entries(vars)
    .filter(([, v]) => v)
    .map(([k, v]) => `${k}:${v}`)
    .join(";");
  if (!decls) return null;

  return <style>{`:root{${decls}}`}</style>;
}
