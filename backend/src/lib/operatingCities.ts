const NORM = new Set(OPERATING_CITIES.map((c) => c.toLowerCase().replace(/ё/g, "е").trim()));

/** Работает ли сервис в этом городе. Пусто → false: город обязателен для повара. */
export function isOperatingCity(city: string | null | undefined): boolean {
  if (!city) return false;
  return NORM.has(city.toLowerCase().replace(/ё/g, "е").trim());
}
